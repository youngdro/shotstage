//! `shotstage commands --markdown`: the API reference (docs/api.md), generated from the catalog
//! so it lists exactly what every entry point accepts.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;
use shotstage_commands::CommandInfo;

/// Section titles for the id prefixes, in reading order.
const GROUPS: &[(&str, &str)] = &[
    ("command", "Session"),
    ("history", "Session"),
    ("scene", "Scene"),
    ("prefab", "Building blocks"),
    ("entity", "Entities"),
    ("mesh", "Meshes"),
    ("model", "Model files"),
    ("image", "Pictures"),
    ("camera", "Cameras"),
    ("pose", "People"),
    ("person", "People"),
    ("light", "Lights"),
    ("motion", "Animation"),
    ("keyframe", "Animation"),
    ("timeline", "Timeline and shots"),
    ("shot", "Timeline and shots"),
    ("storyboard", "Rendering"),
    ("render", "Rendering"),
    ("editor", "Editor view"),
];

fn group_of(id: &str) -> &'static str {
    let prefix = id.split('.').next().unwrap_or(id);
    GROUPS.iter().find(|(p, _)| *p == prefix).map(|(_, g)| *g).unwrap_or("Other")
}

/// Resolve a `$ref` into `$defs` (one level is enough for a readable type name).
fn resolve<'a>(schema: &'a Value, root: &'a Value) -> &'a Value {
    match schema.get("$ref").and_then(Value::as_str) {
        Some(r) => r.rsplit('/').next().and_then(|name| root.get("$defs").and_then(|d| d.get(name))).unwrap_or(schema),
        None => schema,
    }
}

fn type_of(schema: &Value, root: &Value) -> String {
    let s = resolve(schema, root);
    if let Some(e) = s.get("enum").and_then(Value::as_array) {
        return e.iter().filter_map(Value::as_str).map(|v| format!("`{v}`")).collect::<Vec<_>>().join(" \\| ");
    }
    if let Some(one) = s.get("oneOf").or_else(|| s.get("anyOf")).and_then(Value::as_array) {
        let parts: Vec<String> = one
            .iter()
            .map(|o| {
                if let Some(c) = o.get("const").and_then(Value::as_str) {
                    format!("`{c}`")
                } else if let Some(e) = o.get("enum").and_then(Value::as_array) {
                    e.iter().filter_map(Value::as_str).map(|v| format!("`{v}`")).collect::<Vec<_>>().join(" \\| ")
                } else {
                    type_of(o, root)
                }
            })
            .filter(|t| t != "null")
            .collect();
        return parts.join(" \\| ");
    }
    match s.get("type") {
        Some(Value::String(t)) if t == "array" => {
            let item = s.get("items").map(|i| type_of(i, root)).unwrap_or_else(|| "any".into());
            match (s.get("minItems"), s.get("maxItems")) {
                (Some(a), Some(b)) if a == b => format!("[{item}; {a}]"),
                _ => format!("{item}[]"),
            }
        }
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(ts)) => {
            ts.iter().filter_map(Value::as_str).filter(|t| *t != "null").collect::<Vec<_>>().join(" \\| ")
        }
        _ if s.get("properties").is_some() => "object".into(),
        _ => "any".into(),
    }
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|")
}

pub fn markdown(list: &[CommandInfo]) -> String {
    let mut groups: BTreeMap<usize, (&str, Vec<&CommandInfo>)> = BTreeMap::new();
    for c in list {
        let g = group_of(&c.id);
        let order = GROUPS.iter().position(|(_, t)| *t == g).unwrap_or(GROUPS.len());
        groups.entry(order).or_insert((g, vec![])).1.push(c);
    }
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# shotstage API reference\n\n\
_Generated by `shotstage commands --markdown` from the command catalog; do not edit by hand._\n\n\
Every command below is available, with the same parameters and results, from:\n\n\
| Entry point | How to call `camera.frame` |\n| --- | --- |\n\
| Browser | `editor.dispatch(\"camera.frame\", params)` or `await editor.call(\"camera.frame\", params)` |\n\
| CLI | `shotstage run camera.frame '{{...}}' -s shot.json` (or `batch`, `serve`) |\n\
| MCP | tool `camera_frame` (or `command_run` with `{{\"command\": \"camera.frame\", \"params\": {{...}}}}`) |\n\n\
Units: metres, degrees, frames; +Y up, the ground is y = 0, object fronts face +Z, cameras look down -Z. \
Parameters are validated: a missing or unknown field, a wrong type or an out-of-range value returns \
`invalid_params` and leaves the scene unchanged. Commands marked _changes the scene_ are one undo step \
each (a batch is one step for all of its commands).\n\n\
**Host commands** need more than the scene: _gpu_ (rendering), _files_ (reading / writing files: CLI and \
MCP; the desktop editor too), _view_ (the editor's selection and playhead; the CLI and MCP server keep one \
per session). In the browser the rendering ones resolve asynchronously through `editor.call`.\n"
    );
    let _ = writeln!(out, "## Contents\n");
    for (title, cmds) in groups.values() {
        let ids: Vec<String> =
            cmds.iter().map(|c| format!("[`{}`](#{})", c.id, c.id.replace('.', "").to_lowercase())).collect();
        let _ = writeln!(out, "- **{title}**: {}", ids.join(" "));
    }
    for (title, cmds) in groups.values() {
        let _ = writeln!(out, "\n## {title}\n");
        for c in cmds {
            let mut tags = vec![];
            if c.mutates {
                tags.push("changes the scene".to_string());
            } else {
                tags.push("query".to_string());
            }
            if !c.needs.is_empty() {
                tags.push(format!("needs {}", c.needs.join(", ")));
            }
            let _ = writeln!(
                out,
                "### {}\n\n{}  \n_{}_ · MCP tool `{}`\n",
                c.id,
                one_line(&c.summary),
                tags.join(" · "),
                c.id.replace('.', "_")
            );
            let root = &c.params;
            let props = root.get("properties").and_then(Value::as_object);
            let required: Vec<&str> = root
                .get("required")
                .and_then(Value::as_array)
                .map(|r| r.iter().filter_map(Value::as_str).collect())
                .unwrap_or_default();
            match props.filter(|p| !p.is_empty()) {
                None if root.get("oneOf").is_some() || root.get("anyOf").is_some() => {
                    let _ = writeln!(out, "Params: one of several shapes; see `shotstage commands` for the schema.\n");
                }
                None => {
                    let _ = writeln!(out, "No params.\n");
                }
                Some(props) => {
                    let _ = writeln!(out, "| Param | Type | |\n| --- | --- | --- |");
                    for (name, schema) in props {
                        let desc = schema
                            .get("description")
                            .or_else(|| resolve(schema, root).get("description"))
                            .and_then(Value::as_str)
                            .map(one_line)
                            .unwrap_or_default();
                        let req = if required.contains(&name.as_str()) { " **required**" } else { "" };
                        let _ = writeln!(out, "| `{name}`{req} | {} | {desc} |", type_of(schema, root));
                    }
                    let _ = writeln!(out);
                }
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use shotstage_commands::Session;

    #[test]
    fn reference_lists_every_command() {
        let list = Session::default().list();
        let md = super::markdown(&list);
        for c in &list {
            assert!(md.contains(&format!("### {}\n", c.id)), "{}", c.id);
        }
        assert!(!md.contains("## Other"), "every prefix has a section: add it to GROUPS");
    }
}
